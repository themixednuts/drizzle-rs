/// A column definition that can be built in a `const`.
///
/// Primary keys and unique constraints are separate entities
/// ([`PrimaryKeyDef`](super::PrimaryKeyDef),
/// [`UniqueConstraintDef`](super::UniqueConstraintDef)).
///
/// # Examples
///
/// ```
/// use drizzle_types::postgres::ddl::{ColumnDef, IdentityDef, IdentityType};
///
/// const ID: ColumnDef = ColumnDef::new("public", "users", "id", "integer")
///     .not_null()
///     .identity(IdentityDef::new("users_id_seq", IdentityType::Always));
///
/// let column = ID.into_column();
/// assert!(column.identity.is_some());
/// ```
#[derive(Clone, Copy, Debug, PartialEq, Eq, Hash)]
pub struct ColumnDef {
    /// Schema name
    pub schema: &'static str,
    /// Parent table name
    pub table: &'static str,
    /// Column name
    pub name: &'static str,
    /// SQL type, such as `"integer"` or `"varchar(255)"`; for an enum, the
    /// enum's type name
    pub sql_type: &'static str,
    /// Schema of a custom or enum type
    pub type_schema: Option<&'static str>,
    /// `NOT NULL`
    pub not_null: bool,
    /// `DEFAULT` value as SQL
    pub default: Option<&'static str>,
    /// Generated column configuration
    pub generated: Option<GeneratedDef>,
    /// Identity column configuration
    pub identity: Option<IdentityDef>,
    /// Number of array dimensions: `Some(1)` renders `type[]`
    pub dimensions: Option<i32>,
    /// Column comment, emitted as `COMMENT ON COLUMN`
    pub comment: Option<&'static str>,
    /// Collation name (e.g. `"en_US"`, `"C"`, `"POSIX"`, or a custom
    /// `CREATE COLLATION` name). `None` uses the type's default collation and
    /// emits no `COLLATE` clause.
    pub collate: Option<&'static str>,
}

impl ColumnDef {
    /// Creates a nullable column with no default.
    #[must_use]
    pub const fn new(
        schema: &'static str,
        table: &'static str,
        name: &'static str,
        sql_type: &'static str,
    ) -> Self {
        Self {
            schema,
            table,
            name,
            sql_type,
            type_schema: None,
            not_null: false,
            default: None,
            generated: None,
            identity: None,
            dimensions: None,
            comment: None,
            collate: None,
        }
    }

    /// Sets the schema of a custom or enum type.
    #[must_use]
    pub const fn type_schema(self, schema: &'static str) -> Self {
        Self {
            type_schema: Some(schema),
            ..self
        }
    }

    /// Adds `NOT NULL`.
    #[must_use]
    pub const fn not_null(self) -> Self {
        Self {
            not_null: true,
            ..self
        }
    }

    /// Sets the `DEFAULT` value, written as SQL.
    #[must_use]
    pub const fn default_value(self, value: &'static str) -> Self {
        Self {
            default: Some(value),
            ..self
        }
    }

    /// Makes the column `GENERATED ALWAYS AS (expression) STORED`.
    #[must_use]
    pub const fn generated_stored(self, expression: &'static str) -> Self {
        Self {
            generated: Some(GeneratedDef::stored(expression)),
            ..self
        }
    }

    /// Makes the column `GENERATED ALWAYS AS (expression) VIRTUAL`.
    #[must_use]
    pub const fn generated_virtual(self, expression: &'static str) -> Self {
        Self {
            generated: Some(GeneratedDef::virtual_col(expression)),
            ..self
        }
    }

    /// Makes the column an identity column.
    #[must_use]
    pub const fn identity(self, identity: IdentityDef) -> Self {
        Self {
            identity: Some(identity),
            ..self
        }
    }

    /// Sets the number of array dimensions.
    #[must_use]
    pub const fn dimensions(self, dims: i32) -> Self {
        Self {
            dimensions: Some(dims),
            ..self
        }
    }

    /// Sets the column comment.
    #[must_use]
    pub const fn comment(self, comment: &'static str) -> Self {
        Self {
            comment: Some(comment),
            ..self
        }
    }

    /// Sets the column's collation.
    ///
    /// Pass the bare name, such as `en_US`; it is rendered quoted, as in
    /// `COLLATE "en_US"`.
    #[must_use]
    pub const fn collate(self, name: &'static str) -> Self {
        Self {
            collate: Some(name),
            ..self
        }
    }

    /// Converts to the runtime [`Column`].
    #[must_use]
    pub const fn into_column(self) -> Column {
        Column {
            schema: Cow::Borrowed(self.schema),
            table: Cow::Borrowed(self.table),
            name: Cow::Borrowed(self.name),
            sql_type: Cow::Borrowed(self.sql_type),
            type_schema: match self.type_schema {
                Some(s) => Some(Cow::Borrowed(s)),
                None => None,
            },
            not_null: self.not_null,
            default: match self.default {
                Some(s) => Some(Cow::Borrowed(s)),
                None => None,
            },
            generated: match self.generated {
                Some(g) => Some(g.into_generated()),
                None => None,
            },
            identity: match self.identity {
                Some(i) => Some(i.into_identity()),
                None => None,
            },
            dimensions: self.dimensions,
            comment: match self.comment {
                Some(s) => Some(Cow::Borrowed(s)),
                None => None,
            },
            collate: match self.collate {
                Some(s) => Some(Cow::Borrowed(s)),
                None => None,
            },
            ordinal_position: None,
        }
    }
}

impl Default for ColumnDef {
    fn default() -> Self {
        Self::new("public", "", "", "")
    }
}

