use crate::prelude::*;
use crate::{ColumnRef, SQL, SQLParam, SQLSchema, SQLSchemaType, TableRef, ToSQL};
use core::marker::PhantomData;
use core::ops::Deref;

/// Update-model state: no field set yet. Such a model cannot be passed to
/// `.set(...)`, so an `UPDATE` with an empty `SET` does not compile.
pub struct Empty;
/// Update-model state: at least one field set.
pub struct NonEmpty;

/// A type that stands for a SQL name, used to name aliases, CTEs, derived
/// tables and named expressions.
///
/// Define one with [`tag!`](crate::tag). Because the name is part of the
/// type, columns of `users.alias::<U>()` and `users.alias::<V>()` are
/// different types and cannot be mixed up.
pub trait Tag: 'static {
    /// The SQL name.
    const NAME: &'static str;
}

/// Defines a [`Tag`] type in one line.
///
/// # Examples
///
/// ```
/// # use drizzle_core::tag;
/// tag!(UsersAlias, "u");
///
/// let u = UsersAlias; // zero-sized, used as a type parameter
/// assert_eq!(<UsersAlias as drizzle_core::Tag>::NAME, "u");
/// ```
///
/// Visibility is supported:
///
/// ```
/// # use drizzle_core::tag;
/// tag!(pub MyTag, "my_tag");
/// ```
#[macro_export]
macro_rules! tag {
    ($vis:vis $name:ident, $sql_name:expr) => {
        $vis struct $name;
        impl $crate::Tag for $name {
            const NAME: &'static str = $sql_name;
        }
    };
}

/// A value of type `T` labelled with the [`Tag`] `Name` at the type level.
///
/// Dereferences to `T`.
#[derive(Debug, Default, PartialEq, Eq, Hash, PartialOrd, Ord)]
pub struct Tagged<T, Name: Tag> {
    inner: T,
    _tag: PhantomData<fn() -> Name>,
}

impl<T: Copy, Name: Tag> Copy for Tagged<T, Name> {}

impl<T: Copy, Name: Tag> Clone for Tagged<T, Name> {
    fn clone(&self) -> Self {
        *self
    }
}

impl<T, Name: Tag> Tagged<T, Name> {
    /// Wraps `inner`.
    pub const fn new(inner: T) -> Self {
        Self {
            inner,
            _tag: PhantomData,
        }
    }

    /// Returns the wrapped value.
    pub fn into_inner(self) -> T {
        self.inner
    }
}

impl<T, Name: Tag> Deref for Tagged<T, Name> {
    type Target = T;

    fn deref(&self) -> &Self::Target {
        &self.inner
    }
}

/// A table's select, insert, update or partial model, generated by the
/// table macros.
#[diagnostic::on_unimplemented(
    message = "`{Self}` is not a SQL model (Select, Insert, or Update)",
    label = "this type cannot be used as a query model"
)]
pub trait SQLModel<'a, V: SQLParam>: ToSQL<'a, V> {
    /// The columns this model sets or reads, in order.
    ///
    /// Models with a fixed column list return a borrowed slice; others may
    /// allocate.
    fn columns(&self) -> Cow<'static, [ColumnRef]>;
    /// The model's values, comma-separated, in the order of
    /// [`columns`](Self::columns).
    fn values(&self) -> SQL<'a, V>;
}

/// A select model with a partial form, in which each field is optional.
#[diagnostic::on_unimplemented(
    message = "`{Self}` does not support partial field selection",
    label = "this table's Select model does not implement SQLPartial"
)]
pub trait SQLPartial<'a, Value: SQLParam> {
    /// The partial model: every field optional.
    type Partial: SQLModel<'a, Value> + Default + 'a;

    /// Returns an empty partial model.
    #[must_use]
    fn partial() -> Self::Partial {
        Default::default()
    }
}

/// A table for the dialect whose value type is `Value`.
///
/// Generated by `#[SQLiteTable]`, `#[PostgresTable]` and `#[MySQLTable]`,
/// together with the table's models.
#[diagnostic::on_unimplemented(
    message = "`{Self}` is not a SQL table for this dialect",
    label = "ensure this type was derived with #[SQLiteTable], #[PostgresTable], or #[MySQLTable]"
)]
pub trait SQLTable<'a, Type: SQLSchemaType, Value: SQLParam + 'a>:
    SQLSchema<'a, Type, Value> + SQLTableInfo + Default + Clone + Copy
{
    /// The model a selected row decodes into (`SelectUsers`).
    type Select: SQLModel<'a, Value> + SQLPartial<'a, Value> + 'a;
    /// The table's foreign keys.
    type ForeignKeys;
    /// The table's primary key.
    type PrimaryKey;
    /// The table's other constraints.
    type Constraints;

    /// The model for inserting rows (`InsertUsers`). `T` tracks, at the
    /// type level, which fields have been set.
    type Insert<T>: SQLModel<'a, Value> + Default;

    /// The model for updating rows (`UpdateUsers`).
    type Update: SQLModel<'a, Value> + 'a;

    /// This table under the alias `Name`, for self-joins and CTEs.
    type Aliased<Name: Tag + 'static>: SQLTable<'a, Type, Value>;

    /// Returns this table aliased as `Name::NAME`: `"users" AS "u"`.
    fn alias<Name: Tag + 'static>() -> Self::Aliased<Name>;
}

/// A table's metadata as associated constants, generated by the table
/// macros.
///
/// Every `DrizzleTable` also implements [`SQLTableInfo`].
pub trait DrizzleTable: Send + Sync + 'static {
    /// Unqualified table name.
    const NAME: &'static str;

    /// Table name with its schema, if any (`schema.table`).
    const QUALIFIED_NAME: &'static str;

    /// Schema namespace, if any.
    const SCHEMA: Option<&'static str> = None;

    /// Names of tables this table depends on via foreign keys.
    const DEPENDENCY_NAMES: &'static [&'static str] = &[];

    /// Full table metadata.
    const TABLE_REF: TableRef;
}

// Every `DrizzleTable` is a `SQLTableInfo`.
impl<T: DrizzleTable> SQLTableInfo for T {
    fn name(&self) -> &'static str {
        T::NAME
    }

    fn schema(&self) -> Option<&'static str> {
        T::SCHEMA
    }

    fn qualified_name(&self) -> Cow<'static, str> {
        Cow::Borrowed(T::QUALIFIED_NAME)
    }
}

impl<'a, Type, Value, T> SQLTable<'a, Type, Value> for &T
where
    Type: SQLSchemaType,
    Value: SQLParam + 'a,
    T: SQLTable<'a, Type, Value>,
    for<'r> &'r T: SQLSchema<'a, Type, Value> + SQLTableInfo + Default + Clone,
{
    type Select = T::Select;
    type ForeignKeys = T::ForeignKeys;
    type PrimaryKey = T::PrimaryKey;
    type Constraints = T::Constraints;
    type Insert<I> = T::Insert<I>;
    type Update = T::Update;
    type Aliased<Name: Tag + 'static> = T::Aliased<Name>;

    fn alias<Name: Tag + 'static>() -> Self::Aliased<Name> {
        T::alias::<Name>()
    }
}

/// Runtime name information of a table, usable as a trait object.
#[diagnostic::on_unimplemented(
    message = "`{Self}` does not implement SQLTableInfo",
    label = "ensure this type was derived with #[SQLiteTable], #[PostgresTable], or #[MySQLTable]"
)]
pub trait SQLTableInfo: Send + Sync {
    /// Unqualified table name.
    fn name(&self) -> &'static str;

    /// Schema namespace for this table, if any.
    fn schema(&self) -> Option<&'static str> {
        None
    }

    /// Table name with its schema, if any (`schema.table`).
    fn qualified_name(&self) -> Cow<'static, str> {
        self.schema().map_or_else(
            || Cow::Borrowed(self.name()),
            |schema| Cow::Owned(format!("{schema}.{}", self.name())),
        )
    }
}

impl core::fmt::Debug for dyn SQLTableInfo {
    fn fmt(&self, f: &mut core::fmt::Formatter<'_>) -> core::fmt::Result {
        f.debug_struct("SQLTableInfo")
            .field("name", &self.name())
            .field("schema", &self.schema())
            .finish()
    }
}
